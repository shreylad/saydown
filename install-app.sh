#!/bin/bash
# ./install-app.sh            updates the Saydown.app in /Applications with the code in this folder (update_app.py);
#                             restart the app to use it. Nothing is rebuilt or re-signed.
# ./install-app.sh --release  builds dist/Saydown.app and dist/Saydown.dmg: Python and every package are inside the
#                             app, so it needs nothing else installed. Apple Silicon only. Drag it to Applications.
# Needs Apple's Command Line Tools for the compiler (xcode-select --install).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
if [ "${1:-}" != "--release" ]; then
    APP="/Applications/Saydown.app"
    [ -x "$APP/Contents/Resources/python/bin/python3" ] || { echo "No Saydown.app to update: build one with ./install-app.sh --release"; exit 1; }
    exec "$APP/Contents/Resources/python/bin/python3" -B "$HERE/update_app.py" --app "$APP"
fi
APP="$HERE/dist/Saydown.app"
UV="$(command -v uv)" || { echo "uv is not installed: https://docs.astral.sh/uv/"; exit 1; }
RES="$APP/Contents/Resources"
ICON="$APP/Contents/Resources/icon.icns"
# prefer the Command Line Tools compiler: /usr/bin/clang refuses to run until the Xcode licence is accepted
CLT="/Library/Developer/CommandLineTools"
if [ -x "$CLT/usr/bin/clang" ]; then CC="$CLT/usr/bin/clang -isysroot $CLT/SDKs/MacOSX.sdk"; else CC="clang"; fi

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key><string>Saydown</string>
    <key>CFBundleDisplayName</key><string>Saydown</string>
    <key>CFBundleIdentifier</key><string>io.github.saydown</string>
    <key>CFBundleExecutable</key><string>Saydown</string>
    <key>CFBundleIconFile</key><string>icon</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>0.3.2</string>
    <key>LSMinimumSystemVersion</key><string>14.0</string>
    <key>NSPrincipalClass</key><string>NSApplication</string>
    <key>NSHighResolutionCapable</key><true/>
    <key>NSAppTransportSecurity</key><dict><key>NSAllowsLocalNetworking</key><true/></dict>
    <key>NSMicrophoneUsageDescription</key><string>Saydown records your voice while you hold the shortcut, and turns it into text on this Mac.</string>
</dict>
</plist>
EOF

# macOS will not launch an app whose main executable is a script, so a small compiled program is the app:
# it runs launch.sh and shows the window
$CC -O2 -fobjc-arc -framework Cocoa -framework WebKit -o "$APP/Contents/MacOS/Saydown" "$HERE/launcher.m"

# a standalone Python and the packages dictate.py declares, copied into the app
PYHOME="$("$("$UV" python find --managed-python 3.12)" -c 'import sys; print(sys.base_prefix)')"
cp -R "$PYHOME" "$RES/python"
"$UV" export -q --script "$HERE/dictate.py" --no-hashes > "$RES/requirements.txt"
"$UV" pip install -q --python "$RES/python/bin/python3" --target "$RES/site-packages" -r "$RES/requirements.txt"
# mlx-whisper lists torch for converting models, which the app never does; it is half the download
rm -rf "$RES"/site-packages/{torch,torch-*,torchgen,functorch,sympy,sympy-*,networkx,networkx-*,mpmath,mpmath-*,PyObjCTest,setuptools,setuptools-*}
cp "$HERE/dictate.py" "$RES/dictate_bundled.py"
cp "$HERE/runtime_bootstrap.py" "$RES/dictate.py"
cp "$HERE/ui.html" "$RES/"
cat > "$RES/launch.sh" <<'EOF'
#!/bin/bash
# generated by install-app.sh: everything this runs is inside the app, wherever the app is
R="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$HOME/Library/Logs"
export PYTHONUNBUFFERED=1 PYTHONDONTWRITEBYTECODE=1 PYTHONPATH="$R/site-packages"
export SAYDOWN_ICON="$R/icon.icns" SAYDOWN_APP="$(dirname "$(dirname "$R")")"
exec "$R/python/bin/python3" "$R/dictate.py" >> "$HOME/Library/Logs/saydown.log" 2>&1
EOF

# draw the icon: a sage tile with the dark dictation pill on it
ICONSET="$(mktemp -d)/icon.iconset"
mkdir -p "$ICONSET"
"$UV" run -q --with pyobjc-framework-Cocoa python - "$ICONSET" <<'EOF'
import sys
import AppKit

for size in (16, 32, 128, 256, 512):
    for scale in (1, 2):
        px = size * scale
        rep = AppKit.NSBitmapImageRep.alloc().initWithBitmapDataPlanes_pixelsWide_pixelsHigh_bitsPerSample_samplesPerPixel_hasAlpha_isPlanar_colorSpaceName_bytesPerRow_bitsPerPixel_(
            None, px, px, 8, 4, True, False, AppKit.NSDeviceRGBColorSpace, 0, 0)
        AppKit.NSGraphicsContext.setCurrentContext_(AppKit.NSGraphicsContext.graphicsContextWithBitmapImageRep_(rep))
        rounded = AppKit.NSBezierPath.bezierPathWithRoundedRect_xRadius_yRadius_
        colour = AppKit.NSColor.colorWithSRGBRed_green_blue_alpha_
        inset = px * 0.1
        colour(0.86, 0.92, 0.87, 1).setFill()
        rounded(((inset, inset), (px - 2 * inset, px - 2 * inset)), px * 0.18, px * 0.18).fill()
        width, height = px * 0.58, px * 0.22
        colour(0.08, 0.13, 0.10, 1).setFill()
        rounded((((px - width) / 2, (px - height) / 2), (width, height)), height / 2, height / 2).fill()
        dot = height * 0.42
        colour(0.86, 0.92, 0.87, 1).setFill()
        AppKit.NSBezierPath.bezierPathWithOvalInRect_(
            (((px - width) / 2 + height * 0.3, (px - dot) / 2), (dot, dot))).fill()
        AppKit.NSGraphicsContext.currentContext().flushGraphics()
        name = f"{sys.argv[1]}/icon_{size}x{size}{'@2x' if scale == 2 else ''}.png"
        rep.representationUsingType_properties_(AppKit.NSBitmapImageFileTypePNG, {}).writeToFile_atomically_(name, True)
EOF
iconutil -c icns "$ICONSET" -o "$ICON"

# Ad-hoc signatures change when bundled code changes. Routine updates use update_app.py.
codesign --force --deep --sign - "$APP"
touch "$APP"

# ponytail: ad-hoc signed, so macOS asks each downloader to approve it under Privacy & Security;
# sign with a Developer ID and notarise here once there is an Apple Developer account
STAGE="$(mktemp -d)"
cp -R "$APP" "$STAGE/"
ln -s /Applications "$STAGE/Applications"
hdiutil create -quiet -volname Saydown -srcfolder "$STAGE" -ov -format UDZO "$HERE/dist/Saydown.dmg"
echo "Built $APP and $HERE/dist/Saydown.dmg"
echo "On first launch, allow Microphone, Accessibility and Input Monitoring for Saydown, then open it again."
echo "Log: ~/Library/Logs/saydown.log"
