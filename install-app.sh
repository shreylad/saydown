#!/bin/bash
# Builds Saydown.app in /Applications: a small app that owns the window and runs dictate.py from this folder.
# The app is tied to this folder and to your uv install, so run this again if you move either.
# Needs Apple's Command Line Tools for the compiler (xcode-select --install).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
UV="$(command -v uv)" || { echo "uv is not installed: https://docs.astral.sh/uv/"; exit 1; }
APP="/Applications/Saydown.app"
ICON="$APP/Contents/Resources/icon.icns"
# prefer the Command Line Tools compiler: /usr/bin/clang refuses to run until the Xcode licence is accepted
CLT="/Library/Developer/CommandLineTools"
if [ -x "$CLT/usr/bin/clang" ]; then CC="$CLT/usr/bin/clang -isysroot $CLT/SDKs/MacOSX.sdk"; else CC="clang"; fi

rm -rf "$APP" /Applications/open-flow.app  # open-flow was this app's first name
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key><string>Saydown</string>
    <key>CFBundleDisplayName</key><string>Saydown</string>
    <key>CFBundleIdentifier</key><string>io.github.saydown</string>
    <key>CFBundleExecutable</key><string>Saydown</string>
    <key>CFBundleIconFile</key><string>icon</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>0.1</string>
    <key>NSPrincipalClass</key><string>NSApplication</string>
    <key>NSHighResolutionCapable</key><true/>
    <key>NSAppTransportSecurity</key><dict><key>NSAllowsLocalNetworking</key><true/></dict>
    <key>NSMicrophoneUsageDescription</key><string>Saydown records your voice while you hold the shortcut, and turns it into text on this Mac.</string>
</dict>
</plist>
EOF

# macOS will not launch an app whose main executable is a script, so a small compiled program is the app:
# it runs launch.sh and shows the window
$CC -O2 -fobjc-arc -framework Cocoa -framework WebKit -o "$APP/Contents/MacOS/Saydown" "$HERE/launcher.m"

cat > "$APP/Contents/Resources/launch.sh" <<EOF
#!/bin/bash
# generated by install-app.sh
mkdir -p "\$HOME/Library/Logs"
curl -s -m 2 localhost:11434 >/dev/null || open -gja Ollama 2>/dev/null || true   # start the local model server only if it is not already up
export PYTHONUNBUFFERED=1 SAYDOWN_ICON="$ICON" SAYDOWN_APP="$APP"
exec "$UV" run "$HERE/dictate.py" >> "\$HOME/Library/Logs/saydown.log" 2>&1
EOF

# draw the icon: a light blue tile with the black dictation pill on it
ICONSET="$(mktemp -d)/icon.iconset"
mkdir -p "$ICONSET"
"$UV" run -q --with pyobjc-framework-Cocoa python - "$ICONSET" <<'EOF'
import sys
import AppKit

for size in (16, 32, 128, 256, 512):
    for scale in (1, 2):
        px = size * scale
        rep = AppKit.NSBitmapImageRep.alloc().initWithBitmapDataPlanes_pixelsWide_pixelsHigh_bitsPerSample_samplesPerPixel_hasAlpha_isPlanar_colorSpaceName_bytesPerRow_bitsPerPixel_(
            None, px, px, 8, 4, True, False, AppKit.NSDeviceRGBColorSpace, 0, 0)
        AppKit.NSGraphicsContext.setCurrentContext_(AppKit.NSGraphicsContext.graphicsContextWithBitmapImageRep_(rep))
        rounded = AppKit.NSBezierPath.bezierPathWithRoundedRect_xRadius_yRadius_
        colour = AppKit.NSColor.colorWithSRGBRed_green_blue_alpha_
        inset = px * 0.1
        colour(0.82, 0.90, 0.98, 1).setFill()
        rounded(((inset, inset), (px - 2 * inset, px - 2 * inset)), px * 0.18, px * 0.18).fill()
        width, height = px * 0.58, px * 0.22
        colour(0.04, 0.06, 0.10, 1).setFill()
        rounded((((px - width) / 2, (px - height) / 2), (width, height)), height / 2, height / 2).fill()
        dot = height * 0.42
        colour(0.82, 0.90, 0.98, 1).setFill()
        AppKit.NSBezierPath.bezierPathWithOvalInRect_(
            (((px - width) / 2 + height * 0.3, (px - dot) / 2), (dot, dot))).fill()
        AppKit.NSGraphicsContext.currentContext().flushGraphics()
        name = f"{sys.argv[1]}/icon_{size}x{size}{'@2x' if scale == 2 else ''}.png"
        rep.representationUsingType_properties_(AppKit.NSBitmapImageFileTypePNG, {}).writeToFile_atomically_(name, True)
EOF
iconutil -c icns "$ICONSET" -o "$ICON"

# an ad-hoc signature gives macOS a stable identity to attach the permissions to
codesign --force --sign - "$APP"
touch "$APP"

echo "Installed $APP"
echo "Open it from Launchpad, Spotlight or the Applications folder."
echo "On first launch, allow Microphone, Accessibility and Input Monitoring for Saydown, then open it again."
echo "Log: ~/Library/Logs/saydown.log"
